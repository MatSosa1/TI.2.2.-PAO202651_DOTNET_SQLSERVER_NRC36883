    public static void PrintError(string message) => Console.WriteLine("ERROR: " + message);

    /// <summary>Lee el número de una opción entre 1 y <paramref name="maximo"/>.</summary>
    /// <returns>la opción, 0 si se dejó vacío o -1 si no es un número válido</returns>
    public static int ReadOption(string label, int maximo)
    {
        string texto = ReadText(label);
        if (texto.Length == 0)
            return 0;
        return int.TryParse(texto, out int opcion) && opcion >= 1 && opcion <= maximo ? opcion : -1;
    }

    /// <summary>Lee una línea; si la entrada se termina, el programa se despide y sale.</summary>
    public static string ReadText(string label)
    {
        Console.Write(label + ": ");
        string? linea = Console.ReadLine();
        if (linea == null)
        {
            Console.WriteLine();
            PrintMessage("Hasta Luego!");
            Environment.Exit(0);
        }
        return linea.Trim();
    }

    /// <summary>ECUD1 paso 2: la clave se muestra oculta cuando hay una terminal.</summary>
    public static string ReadPassword(string label)
    {
        if (Console.IsInputRedirected)
            return ReadText(label);

        Console.Write(label + ": ");
        var clave = new StringBuilder();
        while (true)
        {
            ConsoleKeyInfo tecla = Console.ReadKey(intercept: true);
            if (tecla.Key == ConsoleKey.Enter)
                break;
            if (tecla.Key == ConsoleKey.Backspace)
            {
                if (clave.Length > 0)
                    clave.Length--;
            }
            else if (!char.IsControl(tecla.KeyChar))
            {
                clave.Append(tecla.KeyChar);
            }
        }
        Console.WriteLine();
        return clave.ToString().Trim();
    }

    /// <summary>Confirmación antes de guardar, importar o eliminar (ECUD2 paso 2, ECUD4 Eliminar paso 2).</summary>
    public static bool Confirm(string question) => "S".Equals(ReadText(question + " (S/N)"), StringComparison.OrdinalIgnoreCase);

    /// <summary>Países, resultados de la API e informes se muestran como tablas de texto (ERS 9.1.1, CLI).</summary>
    public static void PrintTable(string[] headers, List<string[]> rows, bool[] alignRight)
    {
        int[] widths = new int[headers.Length];

        for (int i = 0; i < headers.Length; i++)
        {
            widths[i] = headers[i].Length;
            foreach (string[] row in rows)
                widths[i] = Math.Max(widths[i], row[i].Length);
        }

        Console.WriteLine(Linea(headers, widths, alignRight));

        var separador = new StringBuilder();
        for (int i = 0; i < widths.Length; i++)
            separador.Append(i == 0 ? "" : "-+-").Append(new string('-', widths[i]));
        Console.WriteLine(separador);

        foreach (string[] row in rows)
            Console.WriteLine(Linea(row, widths, alignRight));
    }

    private static string Linea(string[] celdas, int[] widths, bool[] alignRight)
    {
        var texto = new StringBuilder();
        for (int i = 0; i < celdas.Length; i++)
        {
            string celda = alignRight[i] ? celdas[i].PadLeft(widths[i]) : celdas[i].PadRight(widths[i]);
            texto.Append(i == 0 ? "" : " | ").Append(celda);
        }
        return texto.ToString().TrimEnd();
    }
